#!/bin/bash
# Build and run the sequence microbenchmark, and write the results.
#
# Usage: experiments/sequences/run.bash [-r rounds] [-p]
#
#   -r rounds  Time each structure this many times, in turn, and keep the
#              fastest time for each measurement (default 3).
#   -p         Don't measure: only write the results again from the last
#              run's measurements, in build/raw.
#
# Fetches immer (at a fixed commit) into build/, builds build/bench, and
# measures each structure three ways:
#
#   memory     the bytes the structure allocates per element
#   time       nanoseconds per unit, the fastest of 7 runs in each round
#   callgrind  instructions, first-level data cache misses (as callgrind
#              simulates them), and allocations per unit
#
# Writes results.tsv (every number) and results.md (tables of them) in this
# directory. See README.md.

set -euo pipefail

cd "$(dirname "$0")"

rounds=3
do_measure=true
while getopts pr: option; do
    case $option in
        p) do_measure=false ;;
        r) rounds=$OPTARG ;;
        *) exit 2 ;;
    esac
done

cxx=${CXX:-g++-14}
immer_commit=bd4fc749b97dfa2b66a8f3de00bbf234db4856ef
structures=("cons (shared_ptr)" "cons (intrusive)" "cons (free list)" "flat array" "trie" "rrb" "rrb (free list)")

raw=build/raw

if $do_measure; then

mkdir -p build
if [[ ! -d build/immer ]]; then
    git init -q build/immer
    git -C build/immer fetch -q --depth 1 https://github.com/arximboldi/immer.git "$immer_commit"
    git -C build/immer checkout -q FETCH_HEAD
fi

"$cxx" -std=c++26 -O2 -g -DNDEBUG -Wall -Wextra \
    -isystem build/immer bench.cpp -o build/bench

rm -rf "$raw"
mkdir -p "$raw/callgrind"

echo "Measuring memory" >&2
for s in "${structures[@]}"; do
    build/bench memory "$s"
done > "$raw/memory.tsv"

echo "Running callgrind" >&2
slug() { tr -c 'a-z0-9\n' '-' <<< "$1"; }
for s in baseline "${structures[@]}"; do
    printf '%s\0' "$s"
done | xargs -0 -P "$(nproc)" -I{} bash -c '
    s=$1; raw=$2; out=$raw/callgrind/$(tr -c "a-z0-9\n" "-" <<< "$s")
    valgrind --tool=callgrind --cache-sim=yes --callgrind-out-file="$out.out" \
        build/bench callgrind "$s" > "$out.labels" 2> /dev/null
' _ {} "$raw"

# label, units, allocations per unit, instructions per unit, D1 misses per
# unit
for labels in "$raw"/callgrind/*.labels; do
    out=${labels%.labels}.out
    for dump in "$out".*; do
        awk '
            /^desc: Trigger: Client Request: / { sub(/^desc: Trigger: Client Request: /, ""); label = $0 }
            /^summary:/ { print label "\t" $2 "\t" ($6 + $7) }
        ' "$dump"
    done | sort > "$raw/counts.tmp"
    sort "$labels" | join -t $'\t' - "$raw/counts.tmp" |
        awk -F '\t' -v OFS='\t' '{ print $1, $2, $3, $4 / $2, $5 / $2 }'
done > "$raw/callgrind.tsv"
rm "$raw/counts.tmp"

echo "Timing" >&2
for ((round = 0; round < rounds; ++round)); do
    for s in baseline "${structures[@]}"; do
        build/bench time "$s"
    done
done |
    awk -F '\t' -v OFS='\t' '
        !($1 in best) || $2 < best[$1] { best[$1] = $2 }
        END { for (label in best) print label, best[label] }
    ' | sort > "$raw/time.tsv"

fi

# results.tsv: structure, workload, size, instructions, D1 misses,
# allocations, nanoseconds (each per unit), in the order the program runs the
# workloads, by size.
workloads="build|build incrementally|prepend|persistent growth|walk with rest|reduce|reduce spine|length|index|update shared|update unique|concatenate|slice|code: parse|code: evaluate|code: expand|text: concatenate|text: slice|value allocation|memory"
{
    printf 'structure\tworkload\tsize\tinstructions\td1_misses\tallocations\tnanoseconds\n'
    {
        sort "$raw/callgrind.tsv" | join -t $'\t' - "$raw/time.tsv" |
            awk -F '\t' -v OFS='\t' '
                { split($1, key, "|"); printf "%s\t%s\t%s\t%.1f\t%.2f\t%.2f\t%s\n", key[1], key[2], key[3], $4, $5, $3, $6 }
            '
        awk -F '\t' -v OFS='\t' '{ split($1, key, "|"); print key[1], key[2], key[3], "", "", "", $2 }' "$raw/memory.tsv"
    } | awk -F '\t' -v OFS='\t' -v workloads="$workloads" '
        BEGIN { n = split(workloads, w, "|"); for (i = 1; i <= n; ++i) order[w[i]] = i }
        { print order[$2], $0 }
    ' | sort -t $'\t' -s -k1,1n -k4,4n | cut -f 2-
} > results.tsv

# results.md: a table per measure, with a row for each workload and size and
# a column for each structure.
{
    cat <<'EOF'
# Sequence microbenchmark results

Generated by `run.bash`; see README.md for what each workload does and what
the units are. `-` means the workload wasn't run, because the structure makes
it quadratic at that size. Sizes of 0 are workloads with a fixed size of their
own (the code and text workloads).

EOF
    for measure in instructions:4 d1_misses:5 allocations:6 nanoseconds:7; do
        name=${measure%:*}
        column=${measure#*:}
        case $name in
            instructions) title="Instructions per unit" ;;
            d1_misses) title="First-level data cache misses per unit (simulated)" ;;
            allocations) title="Allocations per unit" ;;
            nanoseconds) title="Nanoseconds per unit (the fastest run)" ;;
        esac
        printf '## %s\n\n' "$title"
        awk -F '\t' -v column="$column" -v structures="$(IFS='|'; echo "${structures[*]}")" '
            NR == 1 || $2 == "memory" || $1 == "baseline" { next }
            {
                row = $2 "\t" $3
                if (!(row in seen)) { seen[row] = 1; rows[++count] = row }
                value[row, $1] = $column
            }
            END {
                n = split(structures, s, "|")
                header = "| Workload | Size |"
                rule = "|---|---:|"
                for (i = 1; i <= n; ++i) { header = header " " s[i] " |"; rule = rule "---:|" }
                print header
                print rule
                for (r = 1; r <= count; ++r) {
                    split(rows[r], k, "\t")
                    line = "| " k[1] " | " k[2] " |"
                    for (i = 1; i <= n; ++i) {
                        v = value[rows[r], s[i]]
                        line = line " " (v == "" ? "-" : v) " |"
                    }
                    print line
                }
            }
        ' results.tsv
        printf '\n'
    done
    printf '## Bytes the structure allocates per element\n\n'
    printf 'Not counting the elements'\'' own objects.\n\n'
    awk -F '\t' -v structures="$(IFS='|'; echo "${structures[*]}")" '
        $2 == "memory" {
            if (!($3 in seen)) { seen[$3] = 1; rows[++count] = $3 }
            value[$3, $1] = $7
        }
        END {
            n = split(structures, s, "|")
            header = "| Size |"
            rule = "|---:|"
            for (i = 1; i <= n; ++i) { header = header " " s[i] " |"; rule = rule "---:|" }
            print header
            print rule
            for (r = 1; r <= count; ++r) {
                line = "| " rows[r] " |"
                for (i = 1; i <= n; ++i) line = line " " value[rows[r], s[i]] " |"
                print line
            }
        }
    ' results.tsv
    printf '\n## Baseline\n\n'
    awk -F '\t' '$1 == "baseline" {
        printf "Allocating and freeing a Noeval-sized value (160 bytes, and a separate\nshared_ptr control block): %s instructions, %s ns.\n", $4, $7
    }' results.tsv
} > results.md

echo "Wrote results.tsv and results.md" >&2
